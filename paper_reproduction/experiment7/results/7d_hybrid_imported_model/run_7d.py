# -*- coding: utf-8 -*-
"""
Experiment 7d: Import airbeam_vol.inp, setup TO in CAE, writeInput(), generate .par
manually, run optimization via CLI.

Hybrid approach — proven by 7c findings:
  - CAE Python API works for model creation, TopologyTask, DRESPs, etc.
  - writeParAndInputFiles() has a KeyError bug (can't find prototype job in C++ map)
  - submit() segfaults in the same C++ job lookup code
  - WORKAROUND: writeInput() works fine; generate .par manually; use 'tosca optimize' CLI

This script:
  1. Imports airbeam_vol.inp into CAE
  2. Writes .inp via mdb.jobs['...'].writeInput() (generates CAE-format .inp)
  3. Generates a Tosca .par file manually (matching airbeam_vol.par structure)
  4. Runs 'tosca optimize' CLI subprocess
"""

from abaqus import *
from abaqusConstants import *
from caeModules import *
import os, sys, subprocess, traceback

SEPARATOR = "=" * 70
MAX_CYCLES = int(os.environ.get('ABAQUS_MAX_CYCLES', '80'))

def phase_header(num, total, title):
    print("")
    print(SEPARATOR)
    print("  [{}/{}] {}".format(num, total, title))
    print(SEPARATOR)
    sys.stdout.flush()

def safe_run(label, func):
    try:
        result = func()
        print("  [OK] {}".format(label))
        sys.stdout.flush()
        return True, result
    except Exception as e:
        print("  [FAIL] {}: {} - {}".format(label, type(e).__name__, e))
        traceback.print_exc()
        sys.stdout.flush()
        return False, None

TOTAL = 6

# ============================================================================
# Phase 1: Import the .inp
# ============================================================================
phase_header(1, TOTAL, "Import airbeam_vol.inp into CAE")

ok, model = safe_run("ModelFromInputFile",
    lambda: mdb.ModelFromInputFile(name='airbeam', inputFileName='airbeam_vol.inp'))

if not ok:
    print("FATAL: Cannot import .inp. Aborting.")
    sys.exit(1)

model = mdb.models['airbeam']
if 'Model-1' in mdb.models:
    del mdb.models['Model-1']

assembly = model.rootAssembly

print("  Parts: {}".format(sorted(model.parts.keys())))
print("  Instances: {}".format(sorted(assembly.instances.keys())))
print("  Assembly sets: {}".format(sorted(assembly.sets.keys())))
print("  Steps: {}".format(sorted(model.steps.keys())))

# ============================================================================
# Phase 2: Create prototype job and write input file
# ============================================================================
phase_header(2, TOTAL, "Create prototype job + writeInput()")

ok2a, _ = safe_run("Prototype Job",
    lambda: mdb.Job(name='airbeam_FEA', model='airbeam', numCpus=1, numDomains=1))

ok2b, _ = safe_run("Job.writeInput()",
    lambda: mdb.jobs['airbeam_FEA'].writeInput())

inp_file = 'airbeam_FEA.inp'
if os.path.exists(inp_file):
    print("  Generated: {} ({} bytes)".format(inp_file, os.path.getsize(inp_file)))
else:
    print("FATAL: {} not generated. Aborting.".format(inp_file))
    sys.exit(1)

# ============================================================================
# Phase 3: Generate .par file manually
# ============================================================================
phase_header(3, TOTAL, "Generate Tosca .par file")

# The generated .inp has CAE-format with Part/Instance.
# For Tosca, element sets need instance prefix: PART-1-1.SET_NAME
# But Tosca also supports ALL_ELEMENTS for all elements.
# frozen_elements is at assembly level as FROZEN_ELEMENTS with instance=PART-1-1

# Use the ORIGINAL flat-format .inp (not CAE-format) because Tosca can't resolve
# assembly-level sets from CAE-format .inp files. The original airbeam_vol.inp is
# already in the working directory (copied by SLURM script) and has flat-format
# set names that Tosca understands (lowercase, no instance prefix).
flat_inp = 'airbeam_vol.inp'
print("  Using original flat .inp: {} (Tosca-compatible format)".format(flat_inp))

PAR_CONTENT = """\
! Experiment 7d: Topology Optimization via CAE import + manual .par
! Generated by run_7d.py (hybrid approach)
! Uses original flat-format airbeam_vol.inp (Tosca-compatible)

FEM_INPUT
  ID_NAME                = OPTIMIZATION_MODEL
  FILE                   = {flat_inp}
END_

DV_TOPO
  ID_NAME                = design_variables
  EL_GROUP               = ALL_ELEMENTS
END_

DVCON_TOPO
  ID_NAME                = dvcon_frozen
  EL_GROUP               = frozen_elements
  CHECK_TYPE             = FROZEN
END_

DRESP
  ID_NAME                = DRESP_STRAIN_ENERGY
  DEF_TYPE               = SYSTEM
  TYPE                   = STRAIN_ENERGY
  EL_GROUP               = ALL_ELEMENTS
  GROUP_OPER             = SUM
END_

DRESP
  ID_NAME                = DRESP_VOLUME
  DEF_TYPE               = SYSTEM
  TYPE                   = VOLUME
  EL_GROUP               = ALL_ELEMENTS
  GROUP_OPER             = SUM
END_

OBJ_FUNC
  ID_NAME                = min_SE
  DRESP                  = DRESP_STRAIN_ENERGY
  TARGET                 = MIN
END_

CONSTRAINT
  ID_NAME                = vol_constraint
  DRESP                  = DRESP_VOLUME
  MAGNITUDE              = REL
  LE_VALUE               = 0.5
END_

OPTIMIZE
  ID_NAME                = topology_optimization
  DV                     = design_variables
  OBJ_FUNC               = min_SE
  DVCON                  = dvcon_frozen
  CONSTRAINT             = vol_constraint
  STRATEGY               = TOPO_SENSITIVITY
END_

OPT_PARAM
  ID_NAME                = OPT_PARAMS
  OPTIMIZE               = TOPOLOGY_OPTIMIZATION
END_

STOP
  ID_NAME                = global_stop
  ITER_MAX               = {max_cycles}
END_

SMOOTH
  ID_NAME                = ISO_SMOOTHING
  TASK                   = iso
  ISO_VALUE              = 0.3
  SELF_INTERSECTION_CHECK = runtime
  SMOOTH_CYCLES          = 10
  REDUCTION_RATE         = 60
  REDUCTION_ANGLE        = 5.0
  FORMAT                 = stl
END_
""".format(
    flat_inp=flat_inp,
    max_cycles=MAX_CYCLES,
)

par_file = 'airbeam_7d.par'
with open(par_file, 'w') as f:
    f.write(PAR_CONTENT)
print("  Generated: {} ({} bytes)".format(par_file, os.path.getsize(par_file)))
print("\n  .par content:")
print(PAR_CONTENT)

# ============================================================================
# Phase 4: Save CAE
# ============================================================================
phase_header(4, TOTAL, "Save CAE")

safe_run("saveAs", lambda: mdb.saveAs('airbeam_7d.cae'))

# ============================================================================
# Phase 5: Run Tosca optimization via CLI
# ============================================================================
phase_header(5, TOTAL, "Run 'tosca optimize' via CLI")

print("  Running: tosca optimize -j airbeam_7d_tosca -p {} -s abaqus -scpus 1".format(par_file))
sys.stdout.flush()

# Note: we run this from the current working directory
# tosca optimize requires the .inp and .par to be in the same directory
cmd = [
    'tosca', 'optimize',
    '-j', 'airbeam_7d_tosca',
    '-p', par_file,
    '-s', 'abaqus',
    '-scpus', '1',
]

try:
    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
    )
    stdout, _ = proc.communicate()
    exit_code = proc.returncode

    print("  tosca exit code: {}".format(exit_code))
    # Print last 50 lines of output
    lines = stdout.decode('utf-8', errors='replace').split('\n')
    if len(lines) > 50:
        print("  ... ({} lines total, showing last 50)".format(len(lines)))
        for line in lines[-50:]:
            print("  {}".format(line))
    else:
        for line in lines:
            print("  {}".format(line))
except Exception as e:
    print("  [FAIL] tosca optimize: {} - {}".format(type(e).__name__, e))
    traceback.print_exc()
    exit_code = -1

sys.stdout.flush()

# ============================================================================
# Phase 6: Summary
# ============================================================================
phase_header(6, TOTAL, "Summary")

print("  Import .inp:    OK")
print("  writeInput():   {}".format("OK" if ok2b else "FAIL"))
print("  Generate .par:  OK")
print("  tosca optimize: {}".format("OK (exit {})".format(exit_code) if exit_code == 0 else "FAIL (exit {})".format(exit_code)))

print("\n  Files in CWD:")
for f in sorted(os.listdir('.')):
    if os.path.isdir(f):
        print("    {}/ (dir)".format(f))
    else:
        print("    {} ({} bytes)".format(f, os.path.getsize(f)))

# Check optimization output directory
for d in sorted(os.listdir('.')):
    if os.path.isdir(d):
        print("\n  Contents of {}/".format(d))
        try:
            contents = sorted(os.listdir(d))
            for f2 in contents[:20]:
                print("    {}".format(f2))
            if len(contents) > 20:
                print("    ... and {} more files".format(len(contents) - 20))
        except:
            pass

print("\nExperiment 7d finished.")
sys.stdout.flush()
